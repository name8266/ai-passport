#!/usr/bin/env python3
"""Convert project imagegen sources into flash-resident LVGL RGB565(A8)."""
from pathlib import Path
import struct
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'assets/images/coin-pusher'
OUT=ROOT/'main'


def fit_sprite(atlas, box, size):
    im=atlas.crop(box)
    bounds=im.getchannel('A').getbbox()
    if bounds: im=im.crop(bounds)
    im=im.resize(size,Image.Resampling.LANCZOS)
    result=Image.new('RGBA',size)
    result.alpha_composite(im,((size[0]-im.width)//2,(size[1]-im.height)//2))
    return result


def convert():
    bg=Image.open(SRC/'cabinet-source.png').convert('RGB').resize((240,320),Image.Resampling.LANCZOS)
    atlas=Image.open(SRC/'sprites-source.png').convert('RGBA')
    # This generated atlas has deliberately wide sprite margins; normalized crops.
    w,h=atlas.size
    rects=[(0,.18,.25,.49),(.25,.18,.5,.49),(.5,.18,.75,.49),(.75,.18,1,.49),
           (0,.54,.25,.81),(.27,.54,.44,.81),(.46,.54,.745,.81),(.75,.54,1,.81)]
    names=['copper','gold','ruby','platinum','ball','peg','pusher','flash']
    sizes=[(16,11),(16,11),(16,11),(24,16),(8,8),(4,4),(208,6),(20,20)]
    images=[('background',bg)]+[(n,fit_sprite(atlas,tuple(int(v*(w if j%2==0 else h)) for j,v in enumerate(b)),z)) for n,b,z in zip(names,rects,sizes)]
    declarations=['#pragma once','#include "lvgl.h"']
    code=['/* Generated by tools/convert_coin_assets.py; do not edit manually. */','#include "coin_assets.h"']
    for name,im in images:
        alpha=im.mode=='RGBA'
        data=bytearray()
        for pixel in im.getdata():
            r,g,b=pixel[:3]
            data+=struct.pack('<H',((r>>3)<<11)|((g>>2)<<5)|(b>>3))
        if alpha: data+=bytes(p[3] for p in im.getdata())
        symbol='cp_asset_'+name
        code.append('static const uint8_t '+symbol+'_data[] __attribute__((aligned(4))) = {')
        for start in range(0,len(data),32): code.append('    '+','.join('0x%02x'%v for v in data[start:start+32])+',')
        code.append('};')
        code.append('const lv_image_dsc_t '+symbol+' = { .header={ .magic=LV_IMAGE_HEADER_MAGIC, .cf='+('LV_COLOR_FORMAT_RGB565A8' if alpha else 'LV_COLOR_FORMAT_RGB565')+', .w='+str(im.width)+', .h='+str(im.height)+', .stride='+str(im.width*2)+' }, .data_size=sizeof('+symbol+'_data), .data='+symbol+'_data };')
        declarations.append('extern const lv_image_dsc_t '+symbol+';')
        im.save(SRC/(name+'.png'))
    (OUT/'coin_assets.h').write_text('\n'.join(declarations)+'\n')
    (OUT/'coin_assets.c').write_text('\n'.join(code)+'\n')
    print('Generated',sum(im.width*im.height*(3 if im.mode=='RGBA' else 2) for _,im in images),'asset bytes in flash')

if __name__=='__main__': convert()
