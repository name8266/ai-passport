#!/usr/bin/env python3
"""Convert generated source art into Flash-only, native RGB565/indexed textures.

This is asset export: deterministic band/UV mapping, resize and quantization.
Visual source creation is performed with the built-in image generation tool.
"""
from pathlib import Path
from PIL import Image, ImageOps
import struct

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/images/coin-pusher-realistic-v1'

def rgb565(rgb):
    r, g, b = rgb
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3

def array(name, values, ctype, columns=16):
    fmt = '0x%04x' if ctype == 'uint16_t' else '%d'
    rows = [','.join(fmt % v for v in values[i:i+columns]) for i in range(0,len(values),columns)]
    return 'static const %s %s[%d] __attribute__((aligned(4))) = {\n%s\n};\n' % (ctype,name,len(values),',\n'.join(rows))

def lz4(data):
 out=bytearray();table={};anchor=0;i=0;n=len(data)
 def ext(length):
  while length>=255:out.append(255);length-=255
  out.append(length)
 while i<=n-12:
  key=data[i:i+4];ref=table.get(key);table[key]=i
  if ref is None or i-ref>65535:i+=1;continue
  length=4
  while i+length<n-5 and data[ref+length]==data[i+length]:length+=1
  literals=i-anchor;out.append((min(literals,15)<<4)|min(length-4,15))
  if literals>=15:ext(literals-15)
  out.extend(data[anchor:i]);out.extend(struct.pack('<H',i-ref))
  if length>=19:ext(length-19)
  end=i+length
  for at in range(i+1,end):table[data[at:at+4]]=at
  i=end;anchor=i
 literals=n-anchor;out.append(min(literals,15)<<4)
 if literals>=15:ext(literals-15)
 out.extend(data[anchor:]);return out

cabinet = Image.open(ASSETS / 'cabinet-source.png').convert('RGB')
w,h = cabinet.size
# Generated panel boundaries, mapped onto the existing physical projection.
source = [0,44,129,184,245,276,320]
target = [0,53,145,194,254,275,320]
plate = Image.new('RGB',(240,320))
for a,b,c,d in zip(source,source[1:],target,target[1:]):
    band = cabinet.crop((0,round(a*h/320),w,round(b*h/320)))
    plate.paste(band.resize((240,d-c),Image.Resampling.LANCZOS),(0,c))
plate.save(ASSETS / 'cabinet-240x320.png')
native_plate=Image.new('RGB',(240,320))
native_plate.putdata([((rgb565(c)>>11)*255//31,((rgb565(c)>>5)&63)*255//63,(rgb565(c)&31)*255//31) for c in plate.getdata()])
photo_palette=native_plate.quantize(colors=256,method=Image.Quantize.MEDIANCUT)
photo_indexed=native_plate.quantize(palette=photo_palette,dither=Image.Dither.FLOYDSTEINBERG)
photo_indexed.save(ASSETS/'cabinet-240x320-indexed.png')
photo_colors=photo_indexed.getpalette()
photo_native=[rgb565(photo_colors[k:k+3]) for k in range(0,768,3)]
indices=photo_indexed.tobytes()
plate_pixels=[photo_native[k] for k in indices]
photo_data=bytearray();photo_offsets=[]
for tile in range(10):
    photo_offsets.append(len(photo_data));photo_data.extend(lz4(indices[tile*7680:(tile+1)*7680]))
photo_offsets.append(len(photo_data))
(ASSETS / 'cabinet-240x320.rgb565').write_bytes(struct.pack('<76800H',*plate_pixels))
atlas = Image.open(ASSETS / 'material-atlas-source.png').convert('RGB')
w,h = atlas.size
cells = [atlas.crop((x*w//2,y*h//2,(x+1)*w//2,(y+1)*h//2)).resize((32,32),Image.Resampling.LANCZOS) for y in range(2) for x in range(2)]
text = '#pragma once\n#include <stdint.h>\n/* Generated by tools/convert_pusher_materials.py; immutable Flash assets. */\n'
text += '#if defined(CP_RENDER_HOST) || CP_PHOTO_RGB\n'+array('cp_cabinet_pixels',plate_pixels,'uint16_t')+'#endif\n'
text += array('cp_cabinet_indices',list(indices),'uint8_t',32)
text += array('cp_photo_palette',photo_native,'uint16_t')
text += array('cp_photo_offsets',photo_offsets,'uint32_t')
text += array('cp_photo_data',list(photo_data),'uint8_t',32)
print('Indexed photo:',len(photo_data),'compressed Flash bytes')
steel_strip = cabinet.crop((round(cabinet.width*.15),round(cabinet.height*.59),round(cabinet.width*.85),round(cabinet.height*.73))).resize((240,32),Image.Resampling.LANCZOS)
text += array('cp_steel_rows',[rgb565(steel_strip.getpixel((120,y))) for y in range(32)],'uint16_t')
for name,cell in [('gold',cells[0]),('copper',cells[1])]:
    gray = ImageOps.grayscale(cell)
    # Retain the photographed embossing without confusing material hue with relief.
    lo,hi = gray.getextrema()
    indices = [max(0,min(15,round((v-lo)*15/(hi-lo)))) for v in gray.getdata()]
    text += array('cp_metal_'+name,indices,'uint8_t',32)
    cell.save(ASSETS / (name+'-32.png'))
red,blue = cells[2:]
# Third physical prize uses the red package's luminance with emerald foil.
green = red.copy()
green.putdata([(g,r,b) for r,g,b in red.getdata()])
steel = cabinet.crop((round(cabinet.width*.40),round(cabinet.height*.63),round(cabinet.width*.60),round(cabinet.height*.74))).resize((32,32),Image.Resampling.LANCZOS)
for name,cell in [('red',red),('blue',blue),('green',green),('steel',steel)]:
    indexed = cell.quantize(colors=16,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
    palette = indexed.getpalette()
    text += array('cp_tex_'+name,list(indexed.getdata()),'uint8_t',32)
    text += array('cp_palette_'+name,[rgb565(palette[i*3:i*3+3]) for i in range(16)],'uint16_t')
    text += array('cp_palette_'+name+'_side',[rgb565([v*3//4 for v in palette[i*3:i*3+3]]) for i in range(16)],'uint16_t')
    cell.save(ASSETS / (name+'-32.png'))
def shade(c,f):
    return (min(31,((c>>11)*f)>>12)<<11)|(min(63,(((c>>5)&63)*f)>>12)<<5)|min(31,((c&31)*f)>>12)
gold=rgb565((255,210,75))
for name in ['gold','red','blue','green']:
    if name!='gold':
        cell={'red':red,'blue':blue,'green':green}[name]
        quant=cell.quantize(colors=16,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE);pal=quant.getpalette()
        palette=[rgb565(pal[k*3:k*3+3]) for k in range(16)]
    values=[]
    for light in range(8):
        factor=3072+1024*light//7
        values += [shade(shade(gold,factor),2458+k*200) for k in range(16)] if name=='gold' else [shade(c,factor) for c in palette]
    text+=array('cp_lit_'+name,values,'uint16_t')
(ROOT / 'main/pusher_materials.h').write_text(text)
print('Exported 240x320 cabinet, two embossed coins and four 32x32 indexed materials; no runtime allocation.')
