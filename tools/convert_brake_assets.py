#!/usr/bin/env python3
"""Build indexed textures and the Chinese bitmap font from retained inputs.

Pass --font-source /path/to/NotoSansCJKsc-Regular.otf when expanding the subset.
The original game's display-sized PNGs were recovered losslessly from its
SHA-256-bound firmware. No source artwork or voice recording is synthesized here.
"""
import argparse
import json
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT=Path(__file__).resolve().parent.parent
DEST=ROOT/'assets/images/brake-hero'
FONTS=ROOT/'assets/fonts/brake-hero'
parser=argparse.ArgumentParser();parser.add_argument('--font-source',type=Path)
args=parser.parse_args()
images={p.stem:Image.open(p) for p in sorted((DEST/'source/recovered').glob('*.png'))}
assert len(images)==13
palette=list(next(iter(images.values())).getpalette())
assert len(palette)==768
# Reserve 224..239 for the original low-poly vehicle's materials. Re-map old
# texture pixels to their closest retained color, then store exact final PNGs.
remap=list(range(256))
for i in range(224,240):
    remap[i]=min(range(1,224),key=lambda j:sum((palette[i*3+k]-palette[j*3+k])**2 for k in range(3)))
materials=['f5f1e7','dce1e2','b3bec6','55616e','d7e3e8','121e29','314c60','0b1015',
           'a6b6c2','691927','ff263a','c6a66c','87744f','24313e','a9a49c','ffb44b']
for i,color in enumerate(materials,224):palette[i*3:i*3+3]=bytes.fromhex(color)
out=['/* Generated by tools/convert_brake_assets.py from retained PNG inputs. */','#include "brake_assets.h"']
def array(name,data):
    out.append('const uint8_t '+name+'[] = {')
    for i in range(0,len(data),48):out.append(','.join(map(str,data[i:i+48]))+',')
    out.append('};')
array('bh_palette',bytes(v for i in range(256) for v in (*palette[3*i:3*i+3][::-1],255)))
for name,im in images.items():
    data=bytes(remap[v] for v in im.tobytes())
    array('pixels_'+name,data)
    out.append(f'const bh_sprite_t bh_{name} = {{ {im.width}, {im.height}, pixels_{name} }};')
    p=Image.frombytes('P',im.size,data);p.putpalette(palette);p.save(DEST/'converted'/(name+'.png'),transparency=0)
(DEST/'converted/brake_images.c').write_text('\n'.join(out)+'\n')
strings=[]
for path in ROOT.glob('main/brake*.c'):
    strings+=re.findall(r'"([^"\n]*)"',path.read_text())
chars=set(''.join(strings)+''.join(chr(i) for i in range(32,127)))
chars={c for c in chars if c>=' ' and c!='\\'}
fontpath=FONTS/'NotoSansSC-subset.otf'
source=args.font_source or fontpath
font=TTFont(source)
cmap=font.getBestCmap()
missing=[f'U+{ord(c):04X}' for c in chars if ord(c) not in cmap]
assert not missing,missing
subsetter=subset.Subsetter();subsetter.populate(text=''.join(chars));subsetter.subset(font);font.save(fontpath)
font=ImageFont.truetype(str(fontpath),14)
font_out=['/* Noto Sans SC bitmap subset, SIL OFL 1.1. */','#include "brake_assets.h"','const bh_glyph_t bh_glyphs[] = {']
for c in sorted(chars):
    w=min(14,max(3,round(font.getlength(c))))
    im=Image.new('L',(16,14));ImageDraw.Draw(im).text((0,0),c,font=font,fill=255,anchor='lt')
    bits=[sum(128>>x for x in range(8) if offset+x<w and im.getpixel((offset+x,y))>=80)
          for y in range(14) for offset in (0,8)]
    font_out.append('{'+str(ord(c))+','+str(w)+',{'+','.join(map(str,bits))+'}},')
font_out+=['};',f'const unsigned bh_glyph_count = {len(chars)};']
(FONTS/'brake_font.c').write_text('\n'.join(font_out)+'\n')
(FONTS/'inventory.json').write_text(json.dumps({'size_px':14,'characters':''.join(sorted(chars)),
    'count':len(chars),'missing':missing,'negative_probe':'U+9F98'},ensure_ascii=False,indent=2)+'\n')
print('Generated 13 textures, 16 vehicle materials and',len(chars),'verified glyphs.')
